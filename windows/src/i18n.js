/** Returns the string table of a language, falling back to Persian. */
function stringsFor(code) {
  return STRINGS[code] || STRINGS.fa;
}

/** Returns the metadata of a language, falling back to Persian. */
function languageInfo(code) {
  return LANGUAGES[code] || LANGUAGES.fa;
}

function isRtl(code) {
  return languageInfo(code).rtl;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { STRINGS, LANGUAGES, THEME_MODES, stringsFor, languageInfo, isRtl };
}

// Also expose to the renderer when loaded as a plain <script> in index.html.
if (typeof window !== 'undefined') {
  window.TAKHT_STRINGS = STRINGS;
  window.TAKHT_LANGUAGES = LANGUAGES;
  window.TAKHT_THEME_MODES = THEME_MODES;
}
