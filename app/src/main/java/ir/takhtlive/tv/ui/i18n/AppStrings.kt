/** Languages the interface can be displayed in. */
enum class AppLanguage(val code: String, val label: String, val isRtl: Boolean) {
    PERSIAN("fa", "فارسی", true),
    ENGLISH("en", "English", false),
    ARABIC("ar", "العربية", true);

    companion object {
        fun from(code: String?): AppLanguage =
            entries.firstOrNull { it.code == code } ?: PERSIAN
    }
}

/** Dark / light / follow-system appearance. */
enum class AppThemeMode(val id: String) {
    DARK("dark"),
    LIGHT("light"),
    SYSTEM("system");

    companion object {
        fun from(id: String?): AppThemeMode =
            entries.firstOrNull { it.id == id } ?: DARK
    }
}

